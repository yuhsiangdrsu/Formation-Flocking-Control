def virtual_leader_trajectory(t: float) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """
    Virtual leader trajectory.

    Circular trajectory in x-y, fixed z.

    p_L(t) = [cx + r cos(wt), cy + r sin(wt), z0]
    v_L(t) = [-r w sin(wt), r w cos(wt), 0]
    a_L(t) = [-r w^2 cos(wt), -r w^2 sin(wt), 0]
    """
    p_L = np.array([
        CIRCLE_CENTER[0] + CIRCLE_RADIUS * np.cos(OMEGA * t),
        CIRCLE_CENTER[1] + CIRCLE_RADIUS * np.sin(OMEGA * t),
        FLIGHT_Z,
    ])

    v_L = np.array([
        -CIRCLE_RADIUS * OMEGA * np.sin(OMEGA * t),
         CIRCLE_RADIUS * OMEGA * np.cos(OMEGA * t),
         0.0,
    ])

    a_L = np.array([
        -CIRCLE_RADIUS * OMEGA**2 * np.cos(OMEGA * t),
        -CIRCLE_RADIUS * OMEGA**2 * np.sin(OMEGA * t),
         0.0,
    ])

    return p_L, v_L, a_L


