# Main flocking mission
# ============================================================

def run_flocking_mission(swarm) -> None:
    print("Starting virtual-leader adaptive-pinning flocking mission...")

    mission_start = time.time()
    loop_counter = 0
    log_rows: List[dict] = []

    pinned_agents = np.array([0, 1, 2])

    while True:
        now = time.time()
        t = now - mission_start

        if t >= MISSION_T:
            break

        p, v, _, valid, last_update = mocap.get()

        if not np.all(valid):
            raise RuntimeError("Not all agents have valid OptiTrack data during flocking mission.")

        tracking_age = now - last_update
        if np.any(tracking_age > LOST_TRACKING_TIMEOUT):
            raise RuntimeError("OptiTrack tracking timeout during flocking mission.")

        for i in range(N_AGENTS):
            if not inside_workspace(p[i]):
                raise RuntimeError(f"{CF_NAMES[i]} left workspace: {p[i]}")

        p_L, v_L, _ = virtual_leader_trajectory(t)

        if not inside_workspace(p_L):
            raise RuntimeError(f"Virtual leader outside workspace: {p_L}")

        if loop_counter == 0 or loop_counter % PIN_UPDATE_EVERY == 0:
            pinned_agents = choose_adaptive_pins(
                p=p,
                v=v,
                p_L=p_L,
                v_L=v_L,
                n_pin=N_PIN,
            )

        u_xy, p_L, v_L = compute_control(
            p=p,
            v=v,
            t=t,
            pinned_agents=pinned_agents,
        )

        v_cmd_xy = np.zeros((N_AGENTS, 2))
        p_cmd = np.zeros((N_AGENTS, 3))

        for i in range(N_AGENTS):
            # Acceleration command -> desired x-y velocity.
            v_cmd_xy[i] = v[i, :2] + CONTROL_DT * u_xy[i]

            # Clip desired x-y velocity before converting to position.
            xy_norm = np.linalg.norm(v_cmd_xy[i])
            if xy_norm > V_MAX_XY:
                v_cmd_xy[i] = v_cmd_xy[i] * V_MAX_XY / xy_norm

            # Desired velocity -> short-horizon position setpoint.
            delta_xy = K_VEL_TO_POS * CONTROL_DT * v_cmd_xy[i]

            # Extra guard: do not let the commanded position jump too far in
            # one control cycle, even if K_VEL_TO_POS is increased.
            delta_norm = np.linalg.norm(delta_xy)
            if delta_norm > MAX_POSITION_STEP_XY:
                delta_xy = delta_xy * MAX_POSITION_STEP_XY / delta_norm

            p_cmd[i, 0:2] = p[i, 0:2] + delta_xy
            p_cmd[i, 2] = POSITION_SETPOINT_Z

            if not inside_workspace(p_cmd[i]):
                raise RuntimeError(
                    f"{CF_NAMES[i]} position setpoint outside workspace: "
                    f"current={p[i]}, "
                    f"cmd_x={p_cmd[i,0]:.3f}, "
                    f"cmd_y={p_cmd[i,1]:.3f}, "
                    f"cmd_z={p_cmd[i,2]:.3f}, "
                    f"cmd_vx={v_cmd_xy[i,0]:.3f}, "
                    f"cmd_vy={v_cmd_xy[i,1]:.3f}"
                )

        send_position_commands(swarm, p_cmd)

        pos_err, vel_err = leader_tracking_error(p, v, t)
        cohesion = cohesion_radius_xy(p)
        inter_agent_distances_xy = all_inter_agent_distances_xy(p)
        dmin_now = float(min(inter_agent_distances_xy.values())) if inter_agent_distances_xy else float("inf")

        if SAVE_FLIGHT_LOGS:
            pinned_set_for_log = set(pinned_agents.tolist())
            unpinned_agents = np.array([
                i for i in range(N_AGENTS)
                if i not in pinned_set_for_log
            ])

            for i, name in enumerate(CF_NAMES):
                row = {
                    "time_s": float(t),
                    "loop": int(loop_counter),
                    "agent_id": int(i),
                    "agent_name": name,
                    "x": float(p[i, 0]),
                    "y": float(p[i, 1]),
                    "z": float(p[i, 2]),
                    "vx": float(v[i, 0]),
                    "vy": float(v[i, 1]),
                    "vz": float(v[i, 2]),
                    "leader_x": float(p_L[0]),
                    "leader_y": float(p_L[1]),
                    "leader_z": float(p_L[2]),
                    "leader_vx": float(v_L[0]),
                    "leader_vy": float(v_L[1]),
                    "leader_vz": float(v_L[2]),
                    "leader_pos_error_mean": float(pos_err),
                    "leader_vel_error_mean": float(vel_err),
                    "cohesion_radius_xy": float(cohesion),
                    # Keep the minimum distance for quick safety/debug checks,
                    # but also save every pairwise distance below.
                    "min_inter_agent_distance_xy": float(dmin_now),
                    "ux": float(u_xy[i, 0]),
                    "uy": float(u_xy[i, 1]),
                    "cmd_vx": float(v_cmd_xy[i, 0]),
                    "cmd_vy": float(v_cmd_xy[i, 1]),
                    "cmd_x": float(p_cmd[i, 0]),
                    "cmd_y": float(p_cmd[i, 1]),
                    "cmd_z": float(p_cmd[i, 2]),
                    "is_pinned": int(i in pinned_set_for_log),
                    "pinned_agent_ids": ",".join(str(int(j)) for j in pinned_agents),
                    "pinned_agent_names": ",".join(CF_NAMES[int(j)] for j in pinned_agents),
                    "unpinned_agent_ids": ",".join(str(int(j)) for j in unpinned_agents),
                    "unpinned_agent_names": ",".join(CF_NAMES[int(j)] for j in unpinned_agents),
                }

                # Add all pairwise inter-agent x-y distances to every saved row.
                # For five agents this creates:
                #   dist_xy_cf0_cf1, dist_xy_cf0_cf2, ..., dist_xy_cf3_cf4
                row.update(inter_agent_distances_xy)

                log_rows.append(row)

        if loop_counter % 50 == 0:
            print(
                f"t = {t:5.2f} s | "
                f"pos_err = {pos_err:.3f} m | "
                f"vel_err = {vel_err:.3f} m/s | "
                f"cohesion = {cohesion:.3f} m | "
                f"d_min = {dmin_now:.3f} m | "
                f"pinned = {pinned_agents.tolist()} | "
                f"leader = [{p_L[0]:.2f}, {p_L[1]:.2f}, {p_L[2]:.2f}]"
            )

        loop_counter += 1
        elapsed = time.time() - now
        time.sleep(max(0.0, CONTROL_DT - elapsed))

    # Hold current position briefly before switching from hover commands
    # to position-setpoint landing.
    def _hold_before_landing(scf):
        name = URI_TO_NAME[scf.cf.link_uri]
        agent_id = NAME_TO_INDEX[name]
        pose = mocap.get_agent(agent_id)

        if pose.valid:
            x_hold = float(pose.p[0])
            y_hold = float(pose.p[1])
            z_hold = float(pose.p[2])
        else:
            x_hold = 0.0
            y_hold = 0.0
            z_hold = TAKEOFF_HEIGHT

        for _ in range(10):
            scf.cf.commander.send_position_setpoint(x_hold, y_hold, z_hold, 0.0)
            time.sleep(0.05)

    swarm.parallel_safe(_hold_before_landing)
    save_flocking_log(log_rows)

    print("Flocking mission complete.")


