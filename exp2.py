def send_position_to_cf(scf, position_cmd: np.ndarray) -> None:
    """
    Send Crazyflie position command:
        x, y, z, yaw

    position_cmd = [x_cmd, y_cmd, z_cmd]
    """
    scf.cf.commander.send_position_setpoint(
        float(position_cmd[0]),
        float(position_cmd[1]),
        float(position_cmd[2]),
        float(POSITION_SETPOINT_YAW),
    )


def send_position_commands(swarm, p_cmd: np.ndarray) -> None:
    commands = {
        URIS[CF_NAMES[i]]: p_cmd[i]
        for i in range(N_AGENTS)
    }

    def _send(scf, position_cmd):
        send_position_to_cf(scf, position_cmd)

    swarm.parallel_safe(
        _send,
        args_dict={
            uri: [commands[uri]]
            for uri in URI_LIST
        },
    )


