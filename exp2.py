# Follower-follower distance graph
# ============================================================

def build_follower_neighbors(p: np.ndarray) -> Dict[int, List[int]]:
    """Build distance-based follower graph using x-y distance only."""
    follower_neighbors = {i: [] for i in range(N_AGENTS)}

    for i in range(N_AGENTS):
        for j in range(N_AGENTS):
            if i == j:
                continue

            dist_ij = np.linalg.norm(p[i, :2] - p[j, :2])
            if dist_ij <= R_INTERACTION:
                follower_neighbors[i].append(j)

    return follower_neighbors


# ============================================================
# Collision avoidance
# ============================================================

def compute_potential_avoidance_xy(i: int, p: np.ndarray) -> np.ndarray:
    """Repulsive potential-based collision avoidance in x-y only."""
    u_avoid = np.zeros(2)
    c_act = 1.0 / max(D_ACT - D_MIN, EPS_PHI)

    for j in range(N_AGENTS):
        if j == i:
            continue

        z = p[i, :2] - p[j, :2]
        r = np.linalg.norm(z)

        if r >= D_ACT or r < 1e-12:
            continue

        gap = max(r - D_MIN, EPS_PHI)
        z_hat = z / r
        s = (1.0 / gap) - c_act
        f_mag = K_PHI * s / (gap**2)

        u_avoid += f_mag * z_hat

    return u_avoid


# ============================================================
# Adaptive pinning
# ============================================================

def choose_adaptive_pins(p: np.ndarray, v: np.ndarray, p_L: np.ndarray, v_L: np.ndarray, n_pin: int) -> np.ndarray:
    """
    Select exactly n_pin drones with the largest leader-tracking error.
    Uses x-y states only.
    """
    scores = []

    for i in range(N_AGENTS):
        pos_err = np.linalg.norm(p[i, :2] - p_L[:2])
        vel_err = np.linalg.norm(v[i, :2] - v_L[:2])
        scores.append((pos_err + vel_err, i))

    scores.sort(key=lambda item: item[0], reverse=True)
    return np.array([i for _, i in scores[:n_pin]])


# ============================================================
# Leader-referenced adaptive-pinning flocking controller
# ============================================================

def compute_control(p: np.ndarray, v: np.ndarray, t: float, pinned_agents: np.ndarray) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """
    Crazyflie implementation of the simulation controller in x-y only.

    x-y:
        u_i = a_L - K_FOLLOWER [
                    c_i(x_i - x_L)
                    + sum_j a_ij(x_i - x_j)
              ] + u_avoid_i

    z is not controlled here because the command layer sends a fixed-height
    position setpoint.
    """
    p_L, v_L, a_L = virtual_leader_trajectory(t)
    follower_neighbors = build_follower_neighbors(p)
    pinned_set = set(pinned_agents.tolist())

    u_xy_all = np.zeros((N_AGENTS, 2))
    x_L_xy = np.hstack((p_L[:2], v_L[:2]))

    for i in range(N_AGENTS):
        x_i_xy = np.hstack((p[i, :2], v[i, :2]))

        c_i = PINNING_GAIN if i in pinned_set else 0.0
        e_pin = c_i * (x_i_xy - x_L_xy)

        e_graph = np.zeros(4)
        neigh_i = follower_neighbors[i]

        if len(neigh_i) > 0:
            weights = []

            for j in neigh_i:
                dist_ij = np.linalg.norm(p[i, :2] - p[j, :2])
                a_ij = np.exp(-(dist_ij**2) / (SIGMA_F**2))
                weights.append(a_ij)

            weights = np.array(weights, dtype=float)

            if NORMALIZE_FOLLOWER_WEIGHTS:
                weights = weights / (np.sum(weights) + EPS_W)

            for w_ij, j in zip(weights, neigh_i):
                x_j_xy = np.hstack((p[j, :2], v[j, :2]))
                e_graph += w_ij * (x_i_xy - x_j_xy)

        u_avoid_xy = compute_potential_avoidance_xy(i, p)
        u_xy = a_L[:2] - K_FOLLOWER @ (e_pin + e_graph) + u_avoid_xy
        u_xy = sat_vec(u_xy, A_MAX)

        u_xy_all[i] = u_xy

    return u_xy_all, p_L, v_L


# ============================================================
# Metrics and logging
# ============================================================

def leader_tracking_error(p: np.ndarray, v: np.ndarray, t: float) -> Tuple[float, float]:
    p_L, v_L, _ = virtual_leader_trajectory(t)

    pos_errors = []
    vel_errors = []

    for i in range(N_AGENTS):
        pos_errors.append(np.linalg.norm(p[i, :2] - p_L[:2]))
        vel_errors.append(np.linalg.norm(v[i, :2] - v_L[:2]))

    return float(np.mean(pos_errors)), float(np.mean(vel_errors))


def cohesion_radius_xy(p: np.ndarray) -> float:
    centroid = np.mean(p[:, :2], axis=0)
    return float(np.max(np.linalg.norm(p[:, :2] - centroid, axis=1)))


def all_inter_agent_distances_xy(p: np.ndarray) -> Dict[str, float]:
    """
    Return every pairwise inter-agent x-y distance.

    Example columns in the saved CSV:
        dist_xy_cf0_cf1, dist_xy_cf0_cf2, ...
    """
    distances: Dict[str, float] = {}

    for i in range(N_AGENTS):
        for j in range(i + 1, N_AGENTS):
            name_i = CF_NAMES[i]
            name_j = CF_NAMES[j]
            key = f"dist_xy_{name_i}_{name_j}"
            distances[key] = float(np.linalg.norm(p[i, :2] - p[j, :2]))

    return distances


def min_inter_agent_distance_xy(p: np.ndarray) -> float:
    distances = all_inter_agent_distances_xy(p)

    if len(distances) == 0:
        return float("inf")

    return float(min(distances.values()))


def save_flocking_log(rows: List[dict]) -> None:
    """Save all recorded flocking data to CSV."""
    if not SAVE_FLIGHT_LOGS:
        return

    if len(rows) == 0:
        print("No flocking log rows to save.")
        return

    os.makedirs(LOG_DIR, exist_ok=True)
    csv_path = os.path.join(LOG_DIR, "flocking_log.csv")
    fieldnames = list(rows[0].keys())

    with open(csv_path, mode="w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)

    print(f"Saved flocking log to: {csv_path}")


